def _vallinam_otru(char: str) -> str:
    return {"க": "க்", "ச": "ச்", "த": "த்", "ப": "ப்"}.get(char, "")


def _apply_lexicon(text: str):
    findings = []

    def replace_token(match):
        word = match.group(0)
        if word in TAMIL_LEXICON_CORRECTIONS:
            corrected, reason = TAMIL_LEXICON_CORRECTIONS[word]
            if corrected != word:
                findings.append(
                    {
                        "category": "சொல் / எழுத்து மயக்கத் திருத்தம்",
                        "original": word,
                        "suggestion": corrected,
                        "reason": reason,
                    }
                )
                return corrected
        return word

    result = re.sub(r"[\u0B80-\u0BFF]+", replace_token, text)
    return result, findings


def _apply_morphology(text: str):
    result = text
    findings = []

    for pattern, repl, reason in MORPHOLOGICAL_SUFFIX_RULES:
        for m in re.finditer(pattern, result):
            orig_word = m.group(0)
            new_word = re.sub(pattern, repl, orig_word)
            if orig_word != new_word:
                findings.append(
                    {
                        "category": "உருபனியல் / விகுதிப் பகுப்பாய்வு",
                        "original": orig_word,
                        "suggestion": new_word,
                        "reason": reason,
                    }
                )
        result = re.sub(pattern, repl, result)

    return result, findings


def _apply_phrases(text: str, rules, category: str):
    result = text
    findings = []

    for old, new, reason in rules:
        if old in result:
            result = result.replace(old, new)
            findings.append(
                {
                    "category": category,
                    "original": old,
                    "suggestion": new,
                    "reason": reason,
                }
            )

    return result, findings


def _apply_sandhi(text: str):
    result = text
    findings = []

    for pattern, repl_fn, reason in SANDHI_PATTERNS:
        matches = list(re.finditer(pattern, result))
        for m in matches:
            orig_phrase = m.group(0)
            new_phrase = repl_fn(m)
            if orig_phrase != new_phrase:
                findings.append(
                    {
                        "category": "சந்திப் பிழை (வல்லினம் மிகுதல்)",
                        "original": orig_phrase,
                        "suggestion": new_phrase,
                        "reason": reason,
                    }
                )
        result = re.sub(pattern, repl_fn, result)

    return result, findings


def correct_text(text: str):
    findings = []

    # படி 1: தமிழ் அகராதி & மயங்கொலி எழுத்துத் திருத்தம்
    result, lex_findings = _apply_lexicon(text)
    findings.extend(lex_findings)

    # படி 2: உருபனியல் விகுதிப் பகுப்பாய்வு (-களிள் -> -களில்)
    result, morph_findings = _apply_morphology(result)
    findings.extend(morph_findings)

    # படி 3: கூட்டுவினை / சொற்றொடர் இணைப்பு
    result, phrase_findings = _apply_phrases(
        result, PHRASE_RULES, "சொற்றொடர் / சொல் இணைப்பு"
    )
    findings.extend(phrase_findings)

    # படி 4: சந்திப் பிழைத் திருத்தம் (வல்லினம் மிகும் இடங்கள்)
    result, sandhi_findings = _apply_sandhi(result)
    findings.extend(sandhi_findings)

    # படி 5: இடைவெளி & நிறுத்தற்குறி சீரமைப்பு
    normalized = re.sub(r"[ \t]{2,}", " ", result)
    if normalized != result:
        findings.append(
            {
                "category": "இடைவெளி சீரமைப்பு",
                "original": "இரட்டை / பல இடைவெளிகள்",
                "suggestion": "ஒற்றை இடைவெளி",
                "reason": "அடுத்தடுத்த தேவையற்ற இடைவெளிகள் சீரமைக்கப்பட்டன.",
            }
        )
        result = normalized

    punct_fixed = re.sub(r"\s+([,.;:!?])", r"\1", result)
    if punct_fixed != result:
        findings.append(
            {
                "category": "நிறுத்தற்குறி சீரமைப்பு",
                "original": "நிறுத்தற்குறிக்கு முன் இடைவெளி",
                "suggestion": "இடைவெளி நீக்கப்பட்டது",
                "reason": "காற்புள்ளி, முற்றுப்புள்ளிக்கு முன் இடைவெளி இருக்கக் கூடாது.",
            }
        )
        result = punct_fixed

    return result, findings


def convert_to_official_style(text: str):
    result, findings = _apply_phrases(
        text, OFFICIAL_STYLE_RULES, "அலுவல் மொழிநடை"
    )

    if not findings:
        findings = [
            {
                "category": "அலுவல் மொழிநடை",
                "original": "குறிப்பிட்ட மாற்றம் இல்லை",
                "suggestion": "ஏற்கெனவே அலுவல் நடையில் உள்ளது",
                "reason": "மேலும் மெருகூட்ட 'கலப்பின AI திருத்தம்' பொத்தானைப் பயன்படுத்தலாம்.",
            }
        ]

    notes = [
        f"{item['original']} → {item['suggestion']}: {item['reason']}"
        for item in findings
    ]
    return result, notes
